const assert = require('node:assert/strict');
const R = require('../routing-model.js');
const lan = {lan_ipaddr:'192.168.0.1',lan_netmask:'255.255.255.0',dhcp_enable:'1',dhcp_start:'192.168.0.100',dhcp_end:'192.168.0.149',dhcp_lease_time:'12h'};
assert.deepEqual(R.normalizeLAN({...lan,dhcp_start:'100'}),lan);
assert.equal(R.normalizeLAN({...lan,lan_ipaddr:'192.168.1.1',lan_netmask:'255.255.254.0',dhcp_start:'250',dhcp_end:'280'}).dhcp_end,'192.168.1.24');
assert.equal(R.lease('12h'),43200);assert.equal(R.lease('43200'),43200);
assert.deepEqual(R.lanBody(lan),lan);
for(const value of ['0','-1','1.5h','infinite','999999999999d'])assert.throws(()=>R.lease(value),/duration/);
for(const value of ['192.168.0.256','192.168.00.1','1.2.3','1.2.3.4/path'])assert.throws(()=>R.ipv4(value),/valid/);
for(const [key,value]of [['lan_netmask','255.0.255.0'],['lan_ipaddr','192.168.0.0'],['dhcp_start','192.168.1.20'],['dhcp_end','192.168.0.99'],['dhcp_start','192.168.0.1'],['dhcp_end','192.168.0.255']])assert.throws(()=>R.lanBody({...lan,[key]:value}));
assert.throws(()=>R.lanBody({...lan,lan_ipaddr:'192.168.0.120'}),/pool must not include/);
assert.throws(()=>R.normalizeLAN({lan_ipaddr:'192.168.0.1'}),/incomplete/);
const input={name:'Home server',protocol:'tcp',wan_port:'8443',lan_ip:'192.168.0.10',lan_port:'443',enabled:'1'};
assert.deepEqual(R.portBody(input,lan,[]),{action:'add',...input});
for(const update of [{wan_port:'0'},{lan_port:'65536'},{wan_port:'80-90'},{protocol:'all'},{lan_ip:lan.lan_ipaddr},{lan_ip:'10.0.0.2'},{name:'<img src=x>'}])assert.throws(()=>R.portBody({...input,...update},lan,[]));
assert.throws(()=>R.portBody(input,lan,[{protocol:'tcp+udp',wan_port:'8400-8500'}]),/already belong/);
assert.equal(R.portBody(input,lan,[{protocol:'udp',wan_port:'8443'}]).protocol,'tcp');
assert.equal(R.rules({rule_list:[{name:'a'}]})[0].id,'0');
assert.equal(R.rules({rule_list:[{id:42}]})[0].id,'42');
assert.equal(R.rules({rule_list:[{enabled:true}]})[0].enabled,'1');
assert.deepEqual(R.normalizeSwitches({qos_switch:false,upnp_switch:'on',firewall_switch:'unknown'}),{qos_switch:'0',upnp_switch:'1',firewall_switch:'unknown'});
assert.equal(R.rules({rule_list:[{id:0},{id:'0'}]})[0].removable,false);
assert.throws(()=>R.rules({}),/no usable/);
assert.equal(R.canonical({b:1,a:[{d:2,c:3}]}),R.canonical({a:[{c:3,d:2}],b:1}));
assert.equal(R.reconnectURL('http://router.local:9090','192.168.5.1'),'http://192.168.5.1:9090/#network/lan');
console.log('Passed: subnet-aware DHCP normalization, pool exclusions, lease units, strict IPv4/port validation, overlapping port rules, ambiguous IDs and reconnect addresses.');
