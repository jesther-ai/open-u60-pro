const assert = require('node:assert/strict');
const A = require('../actions.js');
assert.equal(A.encodeSMS('Hi 😀'),'004800690020D83DDE00');
assert.equal(A.smsBody('+63 (917) 000-1234','Hello').number,'+639170001234');
assert.equal(A.smsBody('+1','Hello €').encode_type,'GSM7_default');
assert.equal(A.smsBody('+1','こんにちは').encode_type,'UNICODE');
assert.equal(A.smsBody('+1','hello',new Date(2026,9,26,10,20,30)).sms_time.split(';').slice(0,6).join(';'),'26;10;26;10;20;30');
assert.throws(()=>A.smsBody('Carrier','hello'),/phone number/);
assert.throws(()=>A.smsBody('+1',' '),/Enter a message/);
assert.throws(()=>A.smsBody('+1','x'.repeat(1531)),/1,530/);
assert.equal(A.ids([2,'2',4]),'2;4;');
assert.throws(()=>A.ids(['1;DELETE']),/valid messages/);
assert.throws(()=>A.ids([]),/valid messages/);
assert.equal(A.bands('b3, 1; 3 7',88),'1,3,7');
assert.equal(A.bands('n78,n41',1024),'41,78');
assert.throws(()=>A.bands('0,3',88),/band numbers/);
assert.throws(()=>A.bands('1.2',88),/band numbers/);
A.wifiText('ネットワーク','Network name');
assert.throws(()=>A.wifiText('😀'.repeat(9),'Network name'),/UTF-8 bytes/);
assert.throws(()=>A.wifiText('bad;name','Network name'),/cannot store/);
assert.throws(()=>A.wifiPassword('short'),/8–63/);
assert.throws(()=>A.wifiPassword('password$'),/cannot store/);
A.wifiPassword('longpassword'); A.wifiPassword('f'.repeat(64));
console.log('Passed: Wi-Fi UTF-8 limits and firmware restrictions, password preservation helpers, SMS UTF-16 encoding and recipient validation, read/delete ID encoding, LTE and NR band normalization.');
